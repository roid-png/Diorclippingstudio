import fs from "node:fs";
import path from "node:path";
import type { WordTimestamp } from "./ai-curator.service";
import type { VideoPreset } from "./presets.service";
import { getTempDir } from "./downloader";

function formatAssTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const cs = Math.floor((seconds % 1) * 100);
  return `${h}:${m.toString().padStart(2, "0")}:${s.toString().padStart(2, "0")}.${cs.toString().padStart(2, "0")}`;
}

/**
 * Generates an Advanced SubStation Alpha (.ass) subtitle file tailored to the preset styling,
 * including per-word karaoke / bounce / highlight effects.
 */
export function generateAssSubtitleFile(input: {
  clipId: string;
  clipStartTimeSec: number;
  clipEndTimeSec: number;
  words: WordTimestamp[];
  preset: VideoPreset;
}): string {
  const subStyle = input.preset.subtitleStyle;
  const assDir = getTempDir("temp/subtitles");
  const assFilePath = path.join(assDir, `${input.clipId}.ass`);

  const fontName = subStyle.fontName || "Arial";
  const fontSize = subStyle.fontSize || 24;
  const primaryColor = subStyle.primaryColor || "&H00FFFFFF";
  const highlightColor = subStyle.highlightColor || "&H0000FFFF";
  const outlineColor = subStyle.outlineColor || "&H00000000";
  const outlineWidth = subStyle.outlineWidth || 2;
  const alignment = subStyle.alignment || 2; // Bottom center
  const marginV = subStyle.marginV || 80;
  const bold = subStyle.bold ? -1 : 0;

  // Filter words belonging to this clip time range and offset relative to clip start (0.0s)
  const relativeWords: WordTimestamp[] = input.words
    .filter((w) => w.end >= input.clipStartTimeSec && w.start <= input.clipEndTimeSec)
    .map((w) => ({
      word: w.word,
      start: Math.max(0, w.start - input.clipStartTimeSec),
      end: Math.min(input.clipEndTimeSec - input.clipStartTimeSec, w.end - input.clipStartTimeSec),
    }));

  const assHeader = `[Script Info]
; Script generated by Dior Clipping Engine
Title: Dior Clipping Subtitle
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.601
PlayResX: 1080
PlayResY: 1920

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${fontName},${fontSize * 2.2},${primaryColor},${highlightColor},${outlineColor},&H80000000,${bold},0,0,0,100,100,1,0,1,${outlineWidth * 2},0,${alignment},60,60,${marginV * 2},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  // Group relative words into short readable chunks (3-5 words each)
  const dialogueLines: string[] = [];
  const chunkSize = 4;

  for (let i = 0; i < relativeWords.length; i += chunkSize) {
    const chunk = relativeWords.slice(i, i + chunkSize);
    if (chunk.length === 0) continue;

    const chunkStart = chunk[0]!.start;
    const chunkEnd = Math.max(chunkStart + 0.8, chunk[chunk.length - 1]!.end);

    // Build dialogue with word highlight & bounce
    const chunkDialogueParts: string[] = [];
    chunk.forEach((w) => {
      const cleanWord = w.word.replace(/[{}\\"]/g, "");
      if (subStyle.animation === "bounce-popup") {
        // Bounce pop-up scale and yellow/active highlight
        chunkDialogueParts.push(
          `{\\t(0,80,\\fscx115\\fscy115)\\t(80,160,\\fscx100\\fscy100)\\c${highlightColor}}${cleanWord}{\\c${primaryColor}}`
        );
      } else {
        // Clean highlight without excessive bounce
        chunkDialogueParts.push(`{\\c${highlightColor}}${cleanWord}{\\c${primaryColor}}`);
      }
    });

    const fullLineText = chunkDialogueParts.join(" ");
    dialogueLines.push(
      `Dialogue: 0,${formatAssTime(chunkStart)},${formatAssTime(chunkEnd)},Default,,0,0,0,,${fullLineText}`
    );
  }

  // If no words were detected, create a fallback animated title dialogue
  if (dialogueLines.length === 0) {
    const totalDuration = input.clipEndTimeSec - input.clipStartTimeSec;
    dialogueLines.push(
      `Dialogue: 0,0:00:00.50,${formatAssTime(Math.min(totalDuration, 4.0))},Default,,0,0,0,,{\\c${highlightColor}}Dior Clipping{\\c${primaryColor}} Auto Viral Short`
    );
  }

  const fullAssContent = assHeader + dialogueLines.join("\n") + "\n";
  fs.writeFileSync(assFilePath, fullAssContent, "utf-8");

  return assFilePath;
}

